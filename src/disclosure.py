def catalogue():
    """料金表に出す一覧。何が載るのかを、買う前に見せるためのもの。

    sheet() と同じ定数から作る。片方を直したときに、もう片方が古い
    ままになるのを防ぐ（テストが両者の一致を見る）。
    """
    return [
        ("どの物件でも見る欄",
         [p.where for p in _ALWAYS] + [_ROAD.where, _EXISTING.where]),
        ("診断の結果しだいで足す欄",
         [p.where for p in _CONDITIONAL]),
        ("マンションの場合",
         [p.where for p in _MANSION] + [_MANSION_NOT_IN_35.where]),
    ]


def _hz(enr, name, default=None):
    hz = getattr(enr, "hazard", None) if enr else None
    return getattr(hz, name, default) if hz else default


def sheet(subject, enrichment=None, kind: str = "",
          urbanization: Optional[str] = None) -> List[Point]:
    """この物件で見る欄を並べる。上から順に読める順番にする。"""
    out: List[Point] = list(_ALWAYS)
    is_mansion = "mansion" in (kind or "") or \
        getattr(subject, "exclusive_area_m2", None) is not None
    newbuild = "shinchiku" in (kind or "")

    if not is_mansion:
        out.append(_ROAD)
    if not newbuild:
        out.append(_EXISTING)

    # ---- 区域・ハザード。診断で該当が出たものだけを足す ----
    if urbanization and "調整区域" in urbanization:
        out.append(_URBANIZATION)

    sed = _hz(enrichment, "sediment")
    if sed:
        # 警戒区域と特別警戒区域では、かかる規制がまったく違う。
        # 同じ文言で済ませない。
        out.append(replace(_SEDIMENT, why=(
            f"{sed}に該当する可能性があります。"
            + ("開発の許可と建築物の構造の規制もかかるので、法令に基づく"
               "制限の欄もあわせて見てください。"
               if sed == "特別警戒区域" else
               "警戒区域では建築や開発そのものは制限されません。"
               "かかるのは避難の備えのほうです。"))))

    if _hz(enrichment, "flood_rank"):
        out.append(_FLOOD)
    if _hz(enrichment, "tsunami"):
        out.append(_TSUNAMI)
    if _hz(enrichment, "steep_slope") or _hz(enrichment, "landslide_zone") \
            or _hz(enrichment, "danger_zone"):
        out.append(_OTHER_ZONES)
    if _hz(enrichment, "embankment"):
        out.append(_EMBANKMENT)

    # ---- 建物 ----
    byear = getattr(subject, "build_year", None)
    if byear and byear <= 1981:
        out.append(_QUAKE)
    if byear and byear <= 2006:
        out.append(_ASBESTOS)

    if is_mansion:
        out.extend(_MANSION)
        out.append(_MANSION_NOT_IN_35)

    return out
