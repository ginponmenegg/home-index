# -*- coding: utf-8 -*-
"""重要事項説明書の、どこを見るか。

■なぜ作ったか
重要事項説明書は契約の直前に渡され、宅地建物取引士が読み上げるのを聞く。
30ページ近いものを、その場で初めて見て、聞きながら判断するのは無理がある。
買主が事前に読めるのは「どの欄に何が書かれるか」だけで、それすら普通は
知らされない。

診断ですでに分かっていること（市街化調整区域か、ハザードの区域に入るか、
旧耐震か、区分所有か）から、<b>その物件で特に見るべき欄</b>を先に出す。
契約の前に、読む場所を絞っておくためのもの。

■書かないこと
- <b>買ってよいかは書かない。</b>ここが出すのは「どこに何が書かれるか」と
  「なぜこの物件で効くか」まで。良し悪しの判断は書かない
- <b>重説に書かれない事項を、書かれるものとして並べない。</b>管理費等の
  滞納額は、重要事項説明の記載事項ではなく重要事項調査報告書で分かる。
  そういうものは根拠を分けて書く
- 条文は e-Gov の法令APIで引いて確かめたものだけを載せる。うろ覚えの
  号数を書くと、現場で「そんな欄はない」となる

■根拠の書き方
「法第35条第1項第2号」のように、条・項・号まで書く。担当者に見せたときに
そのまま通じる形にしておく。規則は「規則第16条の4の3第2号」。
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from typing import List, Optional


@dataclass(frozen=True)
class Point:
    """重説の1か所。"""
    where: str      # どの欄か
    law: str        # 根拠条文
    why: str        # なぜこの物件で見るのか


