# -*- coding: utf-8 -*-
"""建物の構造と、それに応じた古さの見方。

■なぜ構造で評価を変えるのか
同じ築30年でも、木造とRCでは建物の残り時間が違う。これまでは築年数だけで
採点していたため、木造30年もRC30年も同じ点になっていた。

■何を基準にするか
国税庁「主な減価償却資産の耐用年数表」の <建物> のうち
「店舗用・住宅用のもの」の法定耐用年数を使う。公開されている数字で、
不動産の実務でも建物価格の減価に使われている。こちらで作った値ではない。

  木造・合成樹脂造                     22年
  木骨モルタル造                       20年
  金属造 骨格材3mm以下                 19年
  金属造 骨格材3mm超4mm以下            27年
  金属造 骨格材4mm超                   34年
  れんが造・石造・ブロック造            38年
  鉄筋コンクリート造・鉄骨鉄筋コンクリート造  47年

  出典：国税庁 主な減価償却資産の耐用年数表（建物）
  https://www.nta.go.jp/taxes/shiraberu/taxanswer/shotoku/pdf/2100_01.pdf

なお法定耐用年数は税法上の区分であって、建物が何年もつかを定めたものでは
ない。ここでは「構造ごとの相対的な差」を測る物差しとしてのみ使う。

■どう効かせるか
築年数をそのまま耐用年数で割ると、木造は22年で満了扱いになり、築25年を
超える木造がほぼ最低点になってしまう。戸建の大半は木造なので、これでは
全体の点数が下がるだけで、比較の役に立たない。

そこで木造を基準（1.0倍）に置き、他の構造は「木造なら何年ぶんに相当するか」
に換算してから、これまでと同じ築年数のカーブに通す。木造の点数は変わらず、
構造の違いだけが差として出る。

  実効築年数 = 築年数 × 22 ÷ その構造の耐用年数

  例）RC造 築30年     → 30 × 22 ÷ 47 = 14年相当
      重量鉄骨 築30年 → 30 × 22 ÷ 34 = 19年相当
      軽量鉄骨 築30年 → 30 × 22 ÷ 23 = 29年相当
"""
from __future__ import annotations

from typing import Optional

# 基準となる構造（戸建の大半が木造のため、ここを1.0倍に置く）
BASE_LIFE = 22

# 軽量鉄骨の23年だけは国税庁の表に無い値。骨格材の厚みで19年と27年に
# 分かれるが、販売図面に厚みが載ることはほとんどない。答えられない項目を
# 増やすより、中間を採って「厚み未確認」と明記するほうが実用的と判断した。
LIGHT_STEEL_NOTE = "骨格材の厚み未確認のため19年と27年の中間"

LIFE = {
    "wood": 22,           # 木造・合成樹脂造（木骨モルタル20年もここに含める）
    "light_steel": 23,    # 軽量鉄骨造（厚み不明・上記の注記のとおり）
    "heavy_steel": 34,    # 重量鉄骨造（骨格材4mm超）
    "rc": 47,             # 鉄筋コンクリート造・鉄骨鉄筋コンクリート造
    "other": 38,          # れんが造・石造・ブロック造など
}

LABEL = {
    "wood": "木造",
    "light_steel": "軽量鉄骨造",
    "heavy_steel": "重量鉄骨造",
    "rc": "RC・SRC造",
    "other": "その他（ブロック造等）",
}

# フォームの選択肢。値はそのまま subj.structure に入る。
CHOICES = [("", "選択しない（不明）"),
           ("wood", "木造（在来・2×4など）"),
           ("light_steel", "軽量鉄骨造"),
           ("heavy_steel", "重量鉄骨造"),
           ("rc", "RC造・SRC造（鉄筋コンクリート）"),
           ("other", "その他（ブロック造・れんが造など）")]

# 表記ゆれを吸収する。並び順が重要。
#   1. SRC/RC を先に見る（「鉄骨鉄筋コンクリート」に「鉄骨」が含まれるため）
#   2. 重量鉄骨を先に見る（「重量鉄骨」に「鉄骨」が含まれるため）
#   3. 残った「鉄骨造」「S造」は軽量として扱う
#
# 3 について。販売図面に「鉄骨造」とだけ書かれていることは珍しくなく、
# 軽量(23年)か重量(34年)かは判別できない。ここで重量と読むと、根拠なく
# 建物の点数を上げてしまう。判断材料が無いときに評価を甘くするのは
# 購入判断の道具として筋が悪いので、低いほうに寄せる。
# フォームは「確認・修正して診断」の作りなので、違えば選び直してもらえる。
_PATTERNS = [
    ("rc", ("ＳＲＣ", "SRC", "鉄骨鉄筋コンクリート", "ＲＣ", "RC",
            "鉄筋コンクリート")),
    ("heavy_steel", ("重量鉄骨", "重鉄")),
    ("light_steel", ("軽量鉄骨", "軽鉄", "鉄骨", "Ｓ造", "S造")),
    ("other", ("ブロック", "れんが", "煉瓦", "石造")),
    ("wood", ("木造", "木骨", "２×４", "2×4", "2x4", "ツーバイフォー",
              "木質", "Ｗ造", "W造", "在来工法")),
]


def normalize(text: Optional[str]) -> Optional[str]:
    """自由記述や選択値を、上の5区分のいずれかに寄せる。判別不能なら None。"""
    if not text:
        return None
    s = str(text).strip()
    if s in LIFE:                 # 既に区分そのもの（フォームの選択値）
        return s
    for key, words in _PATTERNS:
        if any(w in s for w in words):
            return key
    return None


def life_years(key: Optional[str]) -> int:
    """その構造の耐用年数。不明なら木造として扱う（戸建の大半が木造）。"""
    return LIFE.get(key or "", BASE_LIFE)


def effective_age(age: Optional[int], key: Optional[str]) -> Optional[float]:
    """木造なら何年ぶんに相当するかへ換算した築年数。

    構造が不明なら木造として扱うので、値は築年数のまま変わらない。
    """
    if age is None:
        return None
    return age * BASE_LIFE / float(life_years(key))


def label(key: Optional[str]) -> str:
    return LABEL.get(key or "", "構造未確認")
