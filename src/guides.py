"""解説記事。

■なぜアプリの中に置くか
記事の目的は、診断で使っている数字の根拠を開いて見せることにある。
別のブログに置くと、記事と診断が別のサイトの話になってしまう。同じ
ドメインに置き、記事から診断へ、診断から記事へ相互に行き来できるように
する。書き手が誰かは /about に紐づける（YMYLでは書き手が分からない
内容は評価されない）。

■書くときの約束
- **診断で使っている数字だけを書く。** 記事のためだけに調べた数字は
  置かない。src/structure.py や src/config.json に無い値が記事に出て
  きたら、どちらかが間違っている
- **出典を本文に書く。** 「国税庁の表によると」ではなく、どの表の
  どの区分かまで書く
- **断定しないことを断定しない。** 実務で見聞きしただけのことは
  「〜のことが多い」と書く。数えたわけではないので
- **推定価格の話は書かない。** 鑑定評価の法的な整理が済むまでは、
  価格の根拠を解説する記事を出さない

■文章の作り
読み手は、業者の説明を鵜呑みにしたくない買主。機械が量産した記事は
すぐ分かるし、分かった時点で中立性の主張ごと疑われる。次を守る。

- **太字は記事あたり数か所まで。** どこも強調されている文章は、
  どこも強調されていないのと同じ
- **「まとめ」を置かない。** 一度言ったことを最後にもう一度並べ直す
  のは、書き手が読み返していない証拠になる
- **節の長さをそろえない。** 言うことが少ない節は短く終わる
- **箇条書きは、本当に並列なものだけ。** 二つしかない話や、順序の
  ある話は文章で書く
- **最後は実務の一言で終える。** 「何を聞けばいいか」まで書けるのが、
  現場にいる人間の書くものとの差になる

■本文をPythonの文字列で持っている理由
このアプリはテンプレートファイルを持たず、HTMLを文字列定数として
app.py に置いている。記事だけ別の仕組みにすると、置き場が2つになる。
本数が増えて扱いにくくなったら、そのとき分ければよい。

見出しの id と目次は app.py 側で自動生成する。記事に書かせると、
書き忘れたときに目次だけずれる。
"""
