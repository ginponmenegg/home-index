GUIDES: List[Guide] = [_LIGHT_STEEL]


def all_guides() -> List[Guide]:
    """新しい順に並べて返す。"""
    return sorted(GUIDES, key=lambda g: g.published, reverse=True)


def by_slug(slug: str) -> Optional[Guide]:
    for g in GUIDES:
        if g.slug == slug:
            return g
    return None


def paths() -> List[str]:
    """サイトマップに載せるURL。一覧と各記事。"""
    return ["/guide"] + [f"/guide/{g.slug}" for g in all_guides()]
